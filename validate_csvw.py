#!/usr/bin/env python3
"""
validate_csvw.py - Validate a KIParla module's tabular files against CSVW.

The schema is rebuilt from the module's real files with csvw/generate_csvw.py
(so a new or changed <code>.vert.tsv is always covered, whatever the committed
csv-metadata.json says), then every table is checked for column datatypes,
required values and the foreign keys linking the tables (`speaker` and
`participants` to metadata/participants.tsv).

The module is never modified: the generated csv-metadata.json lives in a
temporary directory that links to the module's tsv/ and metadata/.

Usage:
    python validate_csvw.py <module_dir> [--report REPORT.md] [--max-errors N]

Exit code: 0 if the module is valid, 1 if any error was found.
Requires: pip install csvw
"""

import argparse
import collections
import json
import logging
import sys
import tempfile
import warnings
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "csvw"))
import generate_csvw  # noqa: E402


class _Collector(logging.Handler):
    """Collects every message csvw logs, instead of stopping at the first one."""

    def __init__(self):
        super().__init__(level=logging.WARNING)
        self.messages: list[str] = []

    def emit(self, record):
        self.messages.append(record.getMessage())


def validate(module_dir: Path) -> list[str]:
    """Return every validation error of the module (empty list if valid)."""
    from csvw import TableGroup

    module_dir = module_dir.resolve()
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for sub in ("metadata", "tsv"):
            (tmp / sub).symlink_to(module_dir / sub, target_is_directory=True)
        metadata = generate_csvw.build_metadata(module_dir)
        (tmp / "csv-metadata.json").write_text(json.dumps(metadata), encoding="utf-8")

        collector = _Collector()
        log = logging.getLogger(f"validate_csvw.{module_dir.name}")
        log.handlers = [collector]
        log.propagate = False
        log.setLevel(logging.WARNING)

        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            group = TableGroup.from_file(tmp / "csv-metadata.json")
            for table in group.tables:
                try:
                    for _ in table.iterdicts(log=log):
                        pass
                except Exception as exc:  # unreadable file, malformed row, ...
                    collector.messages.append(f"{table.url}: {exc}")
            try:
                group.check_referential_integrity(log=log)
            except Exception as exc:
                collector.messages.append(f"foreign keys: {exc}")

        # the foreign-key pass re-reads the tables, so the same error can be logged twice
        return list(dict.fromkeys(m.replace(str(tmp) + "/", "") for m in collector.messages))


def _file_of(message: str) -> str:
    head = message.split(" ")[0]
    return head.split(":")[0]


def render_report(module: str, errors: list[str], max_errors: int) -> str:
    if not errors:
        return f"`{module}`: the tabular files are valid.\n"
    per_file = collections.Counter(_file_of(e) for e in errors)
    lines = [
        f"`{module}`: {len(errors)} validation error(s) in {len(per_file)} file(s), "
        "checked against the CSVW schema generated by `tools/csvw/generate_csvw.py`.",
        "",
        "| File | Errors |",
        "|---|---|",
    ]
    lines += [f"| `{f}` | {n} |" for f, n in per_file.most_common()]
    lines += ["", f"First {min(max_errors, len(errors))} error(s):", "", "```"]
    lines += errors[:max_errors]
    if len(errors) > max_errors:
        lines.append(f"... and {len(errors) - max_errors} more")
    lines.append("```")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("module_dir", type=Path)
    parser.add_argument("--report", type=Path, help="Write a Markdown report to this file")
    parser.add_argument("--max-errors", type=int, default=50, help="Errors listed in the report (default 50)")
    args = parser.parse_args()

    errors = validate(args.module_dir)
    report = render_report(args.module_dir.resolve().name, errors, args.max_errors)
    print(report)
    if args.report:
        args.report.write_text(report, encoding="utf-8")
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
